// ── Field keys ────────────────────────────────────────────────────────────────
// Exact keys accepted by POST /clinical-records/:id/dictate.
// Must remain in sync with the ClinicalRecord database columns that the
// backend is allowed to classify into.

export type ClinicalDictationFieldKey =
  | 'chiefComplaint'
  | 'anamnesis'
  | 'clinicalEvolution'
  | 'diagnosis'
  | 'proceduresPerformed'
  | 'treatmentPlan'
  | 'prescription'
  | 'recommendations'
  | 'privateNotes'

// ── Request ───────────────────────────────────────────────────────────────────

export type DictateClinicalRecordRequest = {
  /** Base64-encoded audio recorded by the dentist. */
  audioBase64: string
  /** MIME type of the audio, e.g. 'audio/webm' or 'audio/mp4'. */
  mimeType: string
  /** Optional recording duration in seconds (1–120). */
  durationSeconds?: number
}

// ── Odontogram suggestion from the backend ────────────────────────────────────

/**
 * A single tooth-condition suggestion returned by the backend's GPT classification.
 * Tooth numbers are validated FDI strings; condition values match the frontend
 * OdontogramCondition type exactly.
 */
export type DictationOdontogramSuggestion = {
  /** FDI tooth number as a string, e.g. "36". Validated by the backend. */
  toothNumber: string
  /** Lowercase condition key, e.g. "caries". Matches OdontogramCondition values. */
  condition: string
  /** Optional clinical note in Portuguese generated by GPT. */
  notes?: string
  /** GPT confidence: "high" = clearly stated, "medium" = implied, "low" = uncertain. */
  confidence?: 'high' | 'medium' | 'low'
  /** Verbatim fragment from the transcript that triggered this suggestion. */
  sourceText?: string
}

// ── Response ──────────────────────────────────────────────────────────────────

export type DictateClinicalRecordResponse = {
  /** Raw Portuguese transcript returned by Whisper. Shown for dentist review. */
  transcript: string
  /**
   * Whitelisted clinical fields extracted by GPT.
   * Only fields with content will be present — empty fields are omitted.
   * The dentist reviews and applies these; the record is not auto-updated.
   */
  fields: Partial<Record<ClinicalDictationFieldKey, string>>
  /**
   * Tooth-condition suggestions extracted by GPT. Empty array when no specific
   * teeth with conditions were mentioned. The dentist reviews and selects which
   * to apply; the odontogram is NOT auto-updated.
   */
  odontogramSuggestions: DictationOdontogramSuggestion[]
}
